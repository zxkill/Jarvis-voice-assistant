#pragma once

#include <cstdint>
#include "motion_params.h"

/**
 * \file config_store.h
 * \brief Управление настраиваемыми параметрами движения и их постоянным хранением.
 */

namespace ConfigStore {

/**
 * \brief Набор параметров, доступных для оперативной подстройки из веб-интерфейса.
 *
 * Структура содержит только те значения, которые безопасно менять без перепайки
 * и перезагрузки: геометрия шасси, калибровка энкодеров и коэффициенты
 * регуляторов. Аппаратно-зависимые поля (пины, частоты PWM) остаются в Motion::Params.
 */
struct TuningConfig {
  float wheel_diameter_mm = 71.5f;     ///< Диаметр ведущих колёс в миллиметрах.
  float wheel_base_mm     = 235.0f;    ///< База между колёсами в миллиметрах.
  long  tpr_left          = 1368;      ///< Количество тиков за оборот левого колеса.
  long  tpr_right         = 1383;      ///< Количество тиков за оборот правого колеса.
  bool  enc_left_is_enc1  = false;     ///< true, если физический ENC1 подключён к левому колесу.

  float kp_straight_enc   = 20.0f;      ///< Коэффициент по энкодерам для прямолинейного хода.
  float kp_straight_gyro  = 20.0f;      ///< Пропорциональный коэффициент по курсу.
  float ki_straight_gyro  = 0.85f;     ///< Интегральная составляющая корректора курса.

  float kp_turn_enc       = 1.2f;      ///< Вклад энкодеров при повороте на месте.
  float kp_turn_gyro      = 9.0f;      ///< Вклад гироскопа при разворотах.
  float ki_turn_gyro      = 0.07f;      ///< Интегральная составляющая для разворотов.

  float heading_tolerance_deg    = 0.1f;  ///< Допустимое отклонение по углу, при котором поворот завершён.
  float stuck_rate_threshold_dps = 4.0f;  ///< Порог угловой скорости для определения «застревания».
  uint32_t stuck_timeout_ms      = 400;   ///< Таймаут стационарности для срабатывания защиты, мс.
  float yaw_integral_limit       = 40.0f; ///< Ограничение интеграла курса для предотвращения виндапа.

  bool enable_gyro_feedback = true;       ///< Включать ли коррекцию по гироскопу (при наличии датчика).
  bool use_gyro_for_straight = true;      ///< Разрешать ли вклад гироскопа именно для прямого/обратного хода.
  float duty_trim_forward   = 0.0f;       ///< Постоянный трим по duty между левым и правым бортами при движении вперёд (положительный -> усиливаем левый).
  float duty_trim_backward  = 0.0f;       ///< Постоянный трим по duty для движения назад (положительный -> усиливаем левый борт).
};

/**
 * \brief Пара доступности датчиков, необходимых для применения конфигурации.
 */
struct Environment {
  bool gyro_available = false; ///< Обнаружен ли гироскоп во время инициализации.
  uint8_t mpu_i2c_addr = 0;    ///< Используемый адрес MPU (0 если отсутствует).
};

/// Возвращает значение по умолчанию для всех параметров.
TuningConfig defaults();

/// Сообщает хранилищу, какие датчики доступны в текущем запуске.
void set_environment(const Environment& env);

/// Возвращает текущее описание окружения (датчиков).
Environment environment();

/// Устанавливает рабочую конфигурацию в оперативной памяти (без сохранения).
void set_runtime_config(const TuningConfig& cfg);

/// Возвращает актуальную рабочую конфигурацию.
const TuningConfig& current_config();

/**
 * \brief Применяет значения конфигурации к структуре Motion::Params.
 *
 * Функция изменяет только настраиваемые поля и не трогает аппаратно-зависимые
 * параметры (пины, частоты PWM). Используется как при старте системы, так и при
 * онлайн-перенастройке из веб-интерфейса.
 */
void apply_tuning_to_params(const TuningConfig& cfg,
                            Motion::Params& params,
                            const Environment& env);

/**
 * \brief Загружает сохранённые значения из энергонезависимой памяти.
 * @param out Сюда будет записана прочитанная конфигурация.
 * @return true, если данные были прочитаны и прошли валидацию.
 */
bool load_from_storage(TuningConfig& out);

/**
 * \brief Сохраняет переданную конфигурацию в энергонезависимую память.
 *
 * @return true, если запись прошла успешно.
 */
bool save_to_storage(const TuningConfig& cfg);

/**
 * \brief Загружает конфигурацию из хранилища, либо возвращает значения по умолчанию.
 */
TuningConfig load_or_defaults();

/**
 * \brief Перенастраивает модуль Motion с учётом новой конфигурации.
 *
 * На платформе Arduino функция заново вызывает Motion::init(), поэтому её нужно
 * вызывать только когда робот стоит. В десктопных тестах она просто обновляет
 * кэш конфигурации.
 */
bool reconfigure_motion(const TuningConfig& cfg);

/**
 * \brief Обновляет рабочую конфигурацию, сохраняет её и применяет к Motion.
 */
bool update_and_persist(const TuningConfig& cfg);

} // namespace ConfigStore

