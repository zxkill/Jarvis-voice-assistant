#pragma once

#include <cstdint>

namespace Motion {

/**
 * \brief Результат расчёта относительной ошибки прогресса колёс.
 *
 * Помимо самого «ошибочного» значения в условных тиках мы возвращаем
 * нормированные прогрессы левого и правого колёс. Это упрощает детальную
 * диагностику в логах и тестах, поскольку сразу видно, какое колесо ушло вперёд
 * или отстаёт в процентах от целевого пути.
 */
struct ProgressError {
  long  scaled_error_ticks = 0; ///< Ошибка, нормированная и преобразованная обратно в «псевдо-тики».
  float progress_left      = 0; ///< Прогресс левого колеса относительно своей цели (0..1 и выше при переразгоне).
  float progress_right     = 0; ///< Прогресс правого колеса относительно своей цели.
};

/**
 * \brief Результат расчёта симметричных PWM для поворота на месте.
 *
 * Помимо самих значений ШИМ мы сохраняем фактически применённые составляющие
 * (усиление по курсу и поправку по синхронизации), чтобы можно было вывести их
 * в диагностический лог и убедиться, что корректор работает ожидаемо.
 */
struct TurnControlOutput {
  float duty_left      = 0.0f; ///< Расчётный PWM для левого двигателя (до округления и мёртвой зоны).
  float duty_right     = 0.0f; ///< Расчётный PWM для правого двигателя.
  float yaw_component  = 0.0f; ///< Общая «надбавка» к базовому PWM, отвечающая за ускорение/замедление поворота.
  float diff_component = 0.0f; ///< Дифференциальная часть, выравнивающая прогресс колёс.
  float scale_factor   = 1.0f; ///< Коэффициент масштабирования, применённый при ограничении к PWM_MAX.
};

/**
 * \brief Вычисляет согласованную ошибку движения для колёс с разными TPR.
 *
 * Многие шасси имеют немного различающиеся энкодеры/колёса: например, левое
 * колесо может требовать меньше тиков на оборот, чем правое. При простом
 * вычитании «сырых» тиков это приводит к ложной ошибке даже тогда, когда оба
 * колеса продвинулись на одинаковую долю пути. Чтобы корректор не «видел» такую
 * псевдо-ошибку, мы сравниваем прогресс в долях целевых тиков, а затем снова
 * переводим его в эквивалент тиковой ошибки, удобный для существующего PID.
 *
 * @param ticks_left   Текущее количество тиков левого колеса.
 * @param target_left  Целевое количество тиков для левого колеса.
 * @param ticks_right  Текущее количество тиков правого колеса.
 * @param target_right Целевое количество тиков правого колеса.
 *
 * @return Структура с нормированной ошибкой и прогрессом по каждому колесу.
 */
ProgressError compute_progress_error(long ticks_left,
                                     long target_left,
                                     long ticks_right,
                                     long target_right);

/**
 * \brief Вычисляет симметричные PWM для поворота вокруг собственной оси.
 *
 * Функция комбинирует коррекцию по энкодерам и гироскопу так, чтобы обе
 * половины шасси оставались синхронными. Если одно колесо приближается к
 * насыщению PWM, значения автоматически масштабируются, сохраняя соотношение и
 * предотвращая снос робота в сторону при разворотах.
 *
 * @param duty_base    Базовый PWM, задаваемый пользователем.
 * @param kp_enc       Коэффициент усиления по ошибке энкодеров.
 * @param kp_gyro      Пропорциональный коэффициент по курсу.
 * @param ki_gyro      Интегральный коэффициент по курсу.
 * @param err_enc      Ошибка прогресса по энкодерам (условные тики).
 * @param yaw_err_deg  Ошибка по курсу (°), положительна при недовороте.
 * @param yaw_integral Интегральная ошибка (°*с).
 * @param turning_left true, если выполняем поворот влево (левое колесо крутится назад).
 * @param pwm_max      Верхний предел PWM (обычно 2^N-1 для N бит разрешения).
 *
 * @return Структура с симметричными PWM и компонентами коррекции.
 */
TurnControlOutput compute_turn_control(float duty_base,
                                       float kp_enc,
                                       float kp_gyro,
                                       float ki_gyro,
                                       long  err_enc,
                                       float yaw_err_deg,
                                       float yaw_integral,
                                       bool  turning_left,
                                       float pwm_max);

/**
 * \brief Детализированный результат коррекции прямолинейного движения.
 *
 * В отличие от простой «цифры» корректировки мы возвращаем разложение на
 * составляющие. Это позволяет подробно логировать вклад энкодеров и гироскопа,
 * а также понять, применялся ли вообще курс при расчёте.
 */
struct StraightCorrectionOutput {
  float encoder_term      = 0.0f; ///< Вклад ошибки по энкодерам до ограничения.
  float yaw_term          = 0.0f; ///< Пропорциональный вклад гироскопа (0, если выключен).
  float integral_term     = 0.0f; ///< Интегральный вклад по курсу (0, если не используется).
  float combined_raw      = 0.0f; ///< Суммарное значение до насыщения.
  float combined_limited  = 0.0f; ///< Значение после насыщения заданным пределом.
  int   duty_delta        = 0;    ///< Поправка duty-cycle после округления.
  bool  gyro_contribution_used = false; ///< Истина, если гироскоп реально участвовал.
};

StraightCorrectionOutput compute_straight_correction(float kp_enc,
                                                     float kp_gyro,
                                                     float ki_gyro,
                                                     long  err_enc,
                                                     float yaw_err_deg,
                                                     float yaw_integral,
                                                     bool  allow_gyro,
                                                     float correction_limit);

/**
 * \brief Монитор прогресса по энкодерам при отключённом гироскопе.
 *
 * Подробное описание: когда мы временно исключаем вклад гироскопа в прямолинейных
 * проездах, защита от застревания должна опираться исключительно на энкодеры.
 * Структура ниже запоминает последние значения тиков и момент, когда они в
 * последний раз менялись. Это позволяет вовремя остановить робота, если
 * показания «застыли» из-за препятствия или аппаратного сбоя.
 */
struct EncoderProgressMonitor {
  long last_left_ticks = 0;      ///< Последний прогресс левого колеса.
  long last_right_ticks = 0;     ///< Последний прогресс правого колеса.
  uint32_t last_progress_ms = 0; ///< Время последнего изменения в миллисекундах.

  /// Сбрасываем состояние монитора и задаём исходную метку времени.
  void reset(uint32_t now_ms);

  /**
   * \brief Обновляем прогресс и, при необходимости, переносим временную метку.
   *
   * Возвращает `true`, если хотя бы одно колесо изменило количество тиков.
   * Это полезно для детального логирования и расчёта «живых» интервалов.
   */
  bool update(long left_ticks, long right_ticks, uint32_t now_ms);

  /**
   * \brief Проверяем, вышло ли ожидание прогресса за допустимый предел.
   *
   * Если с момента последнего изменения тиков прошло более `timeout_ms`,
   * функция возвращает `true`, сигнализируя вызывающему коду о необходимости
   * мягко завершить манёвр.
   */
  bool is_timed_out(uint32_t now_ms, uint32_t timeout_ms) const;
};

} // namespace Motion

