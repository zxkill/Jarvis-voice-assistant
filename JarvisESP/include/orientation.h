#pragma once

#include <cstdint>

namespace Orientation {

/**
 * \brief Класс-интегратор угла рыскания на основе показаний гироскопа.
 *
 * Вынесен в отдельный модуль без зависимостей от Arduino, чтобы можно было
 * легко покрыть поведение юнит-тестами на хостовой машине. Все временные
 * отметки передаются извне в миллисекундах, что делает класс удобным как для
 * реального железа, так и для моделирования.
 */
class YawIntegrator {
public:
  /**
   * \brief Сброс накопленного угла и инициализация таймеров.
   *
   * @param yaw_deg        Новый текущий угол в градусах, как правило 0.
   * @param timestamp_ms   Метка времени (мс), соответствующая измерению.
   */
  void reset(float yaw_deg = 0.0f, uint32_t timestamp_ms = 0u);

  /**
   * \brief Обновление интегратора новым значением угловой скорости по оси Z.
   *
   * @param gyro_z_dps    Скорость вращения вокруг вертикальной оси, °/с.
   * @param timestamp_ms  Метка времени (мс) текущего измерения.
   */
  void update(float gyro_z_dps, uint32_t timestamp_ms);

  /// Текущий оценённый угол курса в градусах (нормализованный в диапазон [-180°, 180°)).
  float yaw_deg() const { return yaw_deg_wrapped_; }

  /// Непрерывный угол курса без нормализации, растущий при многократных оборотах.
  float yaw_deg_unwrapped() const { return yaw_deg_unwrapped_; }

  /// Последняя измеренная угловая скорость по оси Z (°/с).
  float last_rate_dps() const { return last_rate_dps_; }

  /// Сырая (не скорректированная на смещение) скорость, полезна для отладки.
  float last_raw_rate_dps() const { return last_raw_rate_dps_; }

  /// Текущая оценка систематического смещения гироскопа (°/с).
  float bias_dps() const { return bias_dps_; }

  /**
   * \brief Настройка автоматического компенсатора смещения гироскопа.
   *
   * Компенсатор нужен, чтобы робот не «уплывал» по курсу при стоянке. Мы
   * постепенно усредняем показания, когда считаем что робот неподвижен.
   *
   * @param enabled          Включать ли авто-компенсацию.
   * @param alpha            Коэффициент сглаживания (0..1). Чем больше,
   *                         тем быстрее адаптация к новому смещению.
   * @param threshold_dps    Порог скорости, ниже которого измерение считаем
   *                         «тихим» и используем для оценки смещения.
   * @param settle_ms        Время покоя (мс), которое должно пройти после
   *                         последнего движения, прежде чем трогать смещение.
   */
  void configure_bias(bool enabled, float alpha, float threshold_dps, uint32_t settle_ms);

  /// Возвращает true, если ещё не было ни одного валидного обновления.
  bool is_idle() const { return !has_reference_; }

  /// Возвращает время последнего обновления (мс).
  uint32_t last_update_ms() const { return last_timestamp_ms_; }

  /**
   * \brief Проверка, что робот мог «застрять».
   *
   * Логика проста: если длительное время угловая скорость остаётся меньше
   * порога, значит робот, вероятно, не двигается.
   *
   * @param now_ms            Текущее время (мс).
   * @param rate_threshold    Порог скорости, ниже которого считаем что движения нет.
   * @param stagnation_ms     Время (мс), которое должно пройти в таком состоянии.
   */
  bool is_stuck(uint32_t now_ms, float rate_threshold, uint32_t stagnation_ms) const;

private:
  bool     has_reference_      = false; ///< Были ли обновления после reset().
  float    yaw_deg_unwrapped_  = 0.0f;  ///< Текущий угол без нормализации.
  float    yaw_deg_wrapped_    = 0.0f;  ///< Нормализованный угол (-180..180).
  float    last_rate_dps_      = 0.0f;  ///< Последняя скорректированная угловая скорость.
  float    last_raw_rate_dps_  = 0.0f;  ///< Последняя сырая угловая скорость.
  float    bias_dps_           = 0.0f;  ///< Оценка смещения гироскопа.
  float    bias_alpha_         = 0.05f; ///< Базовый коэффициент для фильтра смещения.
  float    bias_threshold_dps_ = 3.0f;  ///< Порог «тихого» состояния.
  uint32_t bias_settle_ms_     = 300u;  ///< Задержка перед обновлением смещения.
  bool     bias_enabled_       = true;  ///< Флаг включения компенсации смещения.
  uint32_t last_timestamp_ms_  = 0u;    ///< Метка последнего обновления.
  uint32_t last_motion_ms_     = 0u;    ///< Время, когда скорость последний раз была выше порога.
};

} // namespace Orientation

