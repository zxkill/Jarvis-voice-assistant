#pragma once

#include <stdint.h>
#include <vector>

namespace Audio {

/**
 * \brief Результат оценки направления источника звука.
 *
 * Значения подбираются так, чтобы их было удобно отображать как в логах,
 * так и в веб-интерфейсе. Угол отсчитывается от оси робота: положительное
 * значение означает, что сигнал пришёл с левой стороны, отрицательное —
 * с правой.
 */
struct DirectionEstimate {
  float angleDeg = 0.0f;      ///< Расчётный угол прихода волны (градусы).
  float confidence = 0.0f;    ///< Нормированная уверенность [0;1].
  int bestLagSamples = 0;     ///< Найденное смещение между каналами (семплы).
};

/**
 * \brief Вычисляет направление на источник звука по двум каналам.
 *
 * Функция предназначена для чисто численных расчётов и не зависит от Arduino.
 * Её легко тестировать на хосте, генерируя синтетические волны с разной
 * задержкой между микрофонами. Алгоритм ищет максимум нормированной
 * взаимной корреляции в пределах допустимой задержки, после чего переводит
 * найденный лаг в угол с учётом расстояния между микрофонами и скорости звука.
 */
DirectionEstimate estimate_direction(const std::vector<int16_t>& left,
                                     const std::vector<int16_t>& right,
                                     uint32_t sampleRate,
                                     float microphoneSpacingMeters,
                                     float soundSpeed = 343.0f);

/**
 * \brief Рассчитывает среднеквадратичное значение аудиосигнала.
 *
 * Результат нормирован в диапазон 0..1 относительно полного диапазона 16-битных
 * значений. Это удобно для отображения уровня громкости в интерфейсе.
 */
float compute_rms(const std::vector<int16_t>& channel);

} // namespace Audio
